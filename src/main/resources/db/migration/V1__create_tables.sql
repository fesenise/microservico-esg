CREATE SEQUENCE SEQ_ESG_USUARIO
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_ESG_PONTO_COLETA
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_ESG_DESCARTE
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE T_USUARIO (
    ID_USUARIO NUMBER(10) DEFAULT SEQ_ESG_USUARIO.NEXTVAL NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(30) DEFAULT 'USER' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE T_PONTO_COLETA (
    ID_PONTO_COLETA NUMBER(10) DEFAULT SEQ_ESG_PONTO_COLETA.NEXTVAL NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    ENDERECO VARCHAR2(150) NOT NULL,
    CIDADE VARCHAR2(80) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    TIPO_RESIDUO_ACEITO VARCHAR2(80) NOT NULL,
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_PONTO_COLETA PRIMARY KEY (ID_PONTO_COLETA),
    CONSTRAINT CK_PONTO_COLETA_ATIVO CHECK (ATIVO IN (0, 1))
);

CREATE TABLE T_DESCARTE (
    ID_DESCARTE NUMBER(10) DEFAULT SEQ_ESG_DESCARTE.NEXTVAL NOT NULL,
    ID_USUARIO NUMBER(10) NOT NULL,
    ID_PONTO_COLETA NUMBER(10) NOT NULL,
    TIPO_RESIDUO VARCHAR2(80) NOT NULL,
    PESO_KG NUMBER(10,2) NOT NULL,
    DATA_DESCARTE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    OBSERVACAO VARCHAR2(255),
    CONSTRAINT PK_DESCARTE PRIMARY KEY (ID_DESCARTE),
    CONSTRAINT FK_DESCARTE_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES T_USUARIO (ID_USUARIO),
    CONSTRAINT FK_DESCARTE_PONTO FOREIGN KEY (ID_PONTO_COLETA)
        REFERENCES T_PONTO_COLETA (ID_PONTO_COLETA),
    CONSTRAINT CK_DESCARTE_PESO CHECK (PESO_KG > 0)
);